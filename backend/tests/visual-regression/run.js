// Helper to apply visual test config overrides
function getVisualTestConfig(chartType, baseConfig) {
  const overrides = VISUAL_CONFIG_OVERRIDES[chartType];
  if (overrides) {
    return { ...baseConfig, ...overrides };
  }
  return baseConfig;
}

